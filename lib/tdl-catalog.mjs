/**
 * @param {Array} list raw tuples
 * @param {string} group group id for every tuple in this list
 */
function build(list, group) {
  return list.map(([slug, title, category, summary, bullets, tags, keywords, featured]) => ({
    slug,
    id: slug,
    title,
    category,
    group,
    summary,
    detail: bullets || [],
    tags: tags || [],
    keywords: keywords || [],
    featured: Boolean(featured),
    href: `/shop#${slug}`,
  }));
}

