// CHANGE: 2026-10-23 — NEW: the `/shop` catalogue (single source of truth for every TDL,
// Excel importer, business booster and industry module we offer).
//
// WHY: the owner supplied an Excel sheet of 100+ TDLs and asked for a proper `/shop` catalogue
// (search, sort, buy, sidebar, details, responsive) while `/addons` and `/modules` stay as they
// are. The sheet is NOT shipped and NOT parsed at runtime (a browser cannot read an xlsx, and a
// build-time parse would break the moment the file moves). The list below is the sheet, cleaned
// once, into plain data.
//
// HARD RULES inherited from the owner's brief:
//   1. NO PRICES. The sheet's `Standard Price` / MU / SU / discount columns are deliberately
//      dropped. Not one price field exists in this module, so no page can leak one by accident.
//   2. NO single-user vs multi-user split. The owner only wants to show that the item EXISTS.
//   3. Every item is a lead, not a checkout: "Buy" opens the enquiry form (no cart, no payment).
//
// Pure ESM, zero dependencies (same pattern as lib/addons.mjs, lib/prices-catalog.mjs) so the
// chat route, the offline Sara fallback and the plain-Node test suites can read the same data.
// lib/tdl-catalog.ts is the typed facade; lib/tdl-catalog.d.mts types this file.
//
// FIELD NOTES
//   slug      stable id, also the deep link anchor: /shop#<slug>
//   group     the sheet the item came from (addon | excel | booster | module) -> top filter
//   category  what the item DOES (9 buckets) -> sidebar filter
//   summary   one plain-language sentence shown on the card
//   detail    extra bullets shown in the detail panel (may be empty)
//   tags      short chips shown on the card / detail panel
//   keywords  matching terms for Ask Sara / Learn Sara (never rendered)

